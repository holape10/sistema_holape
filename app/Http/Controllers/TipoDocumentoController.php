    public function consultartipodocumento(Request $request){

        $search = $request->term;     
        $doccomprobante = DB::tABLE('tipo_documento')->where('tdoest','=','Activo')->orderBy('tdocod','asc')->where('tdodes','like','%'.$search.'%')->get();
        $results = array();
        foreach($doccomprobante as $comp){
            $results[] = ['id'=>$comp->tdocod,'text'=>$comp->tdodes];
        }

        return response()->json($results);
    }
